# Also generate TypeScript code to append
def to_ts(val, indent=4):
    """Convert Python value to TypeScript literal"""
    pad = ' ' * indent
    if isinstance(val, str):
        escaped = val.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n")
        return f"'{escaped}'"
    elif isinstance(val, bool):
        return 'true' if val else 'false'
    elif isinstance(val, (int, float)):
        return str(val)
    elif isinstance(val, list):
        if not val:
            return '[]'
        items = [f"{pad}{to_ts(item, indent+2)}" for item in val]
        return '[\n' + ',\n'.join(items) + f',\n{pad[:-2]}]'
    elif isinstance(val, dict):
        if not val:
            return '{}'
        items = []
        for k, v in val.items():
            ts_val = to_ts(v, indent+2)
            items.append(f"{pad}{k}: {ts_val},")
        return '{\n' + '\n'.join(items) + pad[:-2] + '}'
    elif val is None:
        return 'undefined'
    return str(val)

